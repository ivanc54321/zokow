// Helper to attach coordinates and venueId to each event
export function getEventCoords(event) {
  if (event.coords) return event.coords;
  const title = (event.title || '').toLowerCase();
  const venue = (event.venue || '').toLowerCase();
  const town = (event.town || '').toLowerCase();

  if (venue.includes('dreamland') || title.includes('dreamland') || title.includes('hall by the sea')) {
    return [51.3855, 1.3785];
  }
  if (venue.includes('hartsdown') || title.includes('hartsdown')) {
    return [51.3780, 1.3710];
  }
  if (venue.includes('walpole')) {
    return [51.3935, 1.4080];
  }
  if (venue.includes('turner contemporary')) {
    return [51.3912, 1.3865];
  }
  if (venue.includes('ramsgate music hall')) {
    return [51.3340, 1.4210];
  }
  if (venue.includes('botany bay')) {
    return [51.3885, 1.4350];
  }
  if (venue.includes('viking bay') || town === 'broadstairs') {
    return [51.3585, 1.4420];
  }
  if (town === 'ramsgate') {
    return [51.3360, 1.4172];
  }
  return [51.3892, 1.3835]; // Margate default
}

export function getEventVenueId(event) {
  const text = (event.venue + ' ' + event.title).toLowerCase();
  if (text.includes('dreamland') || text.includes('hall by the sea')) return 'dreamland';
  if (text.includes('hartsdown')) return 'hartsdown';
  if (text.includes('walpole')) return 'walpole';
  if (text.includes('turner contemporary')) return 'turner';
  if (text.includes('ramsgate music hall')) return 'ramsgatemusichall';
  return null;
}

